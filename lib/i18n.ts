const localeIndex: Record<Exclude<UiLanguage, "en" | "ar">, number> = { es: 0, "zh-CN": 1, "pt-BR": 2, fr: 3 };

export function translate(source: string, language: UiLanguage = "en", values: Record<string, string | number> = {}): string {
  const found = catalog[source];
  let output = language === "en" || !found
    ? source
    : language === "ar"
      ? (arabicCatalog[source] ?? source)
      : found[localeIndex[language]];
  for (const [key, value] of Object.entries(values)) output = output.replaceAll(`{${key}}`, String(value));
  return output;
}

export function useI18n() {
  const { prefs } = usePrefs();
  const language: UiLanguage = UI_LANGUAGES.some((item) => item.code === prefs.uiLanguage)
    ? (prefs.uiLanguage as UiLanguage)
    : "en";
  return { language, t: (source: string, values?: Record<string, string | number>) => translate(source, language, values) };
}
